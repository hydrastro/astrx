fn crumb_bar(
    ctx: &Ctx,
    repo_name: &str,
    reference: &str,
    path: &str,
    leaf_is_blob: bool,
) -> String {
    let mut crumbs = vec![format!(
        "<a href=\"{}\">{}</a>",
        esc(&ctx.action(repo_name, "tree", &[("ref", reference)])),
        esc(repo_name)
    )];
    let parts: Vec<&str> = path.split('/').filter(|p| !p.is_empty()).collect();
    let mut accum = String::new();
    for (idx, part) in parts.iter().enumerate() {
        if accum.is_empty() {
            accum = (*part).to_string();
        } else {
            accum = format!("{accum}/{part}");
        }
        if idx == parts.len() - 1 && leaf_is_blob {
            crumbs.push(esc(part));
        } else {
            let url = ctx.action(repo_name, "tree", &[("ref", reference), ("path", &accum)]);
            crumbs.push(format!("<a href=\"{}\">{}</a>", esc(&url), esc(part)));
        }
    }
    format!(
        "<div class=\"crumbs mono\">{} <span class=\"pill\">{}</span></div>",
        crumbs.join(" <span class=\"muted\">/</span> "),
        esc(reference)
    )
}

/// The branch/tag/permalink choices the ref switcher offers, shared by the tree
/// and blob views.
#[derive(Clone, Copy, Debug, Default)]
pub struct RefChoices<'a> {
    /// Branch names to offer.
    pub branches: &'a [String],
    /// Tag names to offer.
    pub tags: &'a [String],
    /// The resolved commit sha behind the current ref, for the permalink
    /// (empty to omit it).
    pub commit_sha: &'a str,
}

/// A rendered README to append below a listing (`html`), plus the filename to
/// title the box with (`name`, defaulting to `README`).
#[derive(Clone, Copy, Debug, Default)]
pub struct Readme<'a> {
    /// The already-safe rendered HTML, or `None` for no README box at all.
    pub html: Option<&'a str>,
    /// The README's filename.
    pub name: Option<&'a str>,
}

/// A no-JS ref switcher (HTML5 `<details>`) plus a sha-pinned permalink.
///
/// Every entry is a plain link that keeps the current `action`/`path` and only
/// swaps the ref, so switching branches/tags needs neither JavaScript nor a form
/// (our CSP forbids submitting one anywhere but `self`). The permalink pins the
/// current view to the resolved commit sha for a stable, immutable URL.
#[must_use]
pub fn ref_switcher(
    ctx: &Ctx,
    repo_name: &str,
    action: &str,
    reference: &str,
    path: &str,
    choices: &RefChoices<'_>,
) -> String {
    let links = |names: &[String]| -> String {
        if names.is_empty() {
            return "<span class=\"muted\">none</span>".to_string();
        }
        names
            .iter()
            .map(|name| {
                let url = ctx.action(repo_name, action, &[("ref", name), ("path", path)]);
                let marker = if name == reference { " &check;" } else { "" };
                format!("<a href=\"{}\">{}{marker}</a>", esc(&url), esc(name))
            })
            .collect::<Vec<_>>()
            .join(" ")
    };
    let mut out =
        String::from("<details class=\"switch\"><summary>Switch ref &amp; permalink</summary>");
    out.push_str("<div class=\"menu\">");
    out.push_str(&format!(
        "<div><strong>Branches:</strong> {}</div>",
        links(choices.branches)
    ));
    out.push_str(&format!(
        "<div><strong>Tags:</strong> {}</div>",
        links(choices.tags)
    ));
    if !choices.commit_sha.is_empty() {
        let perma = ctx.action(
            repo_name,
            action,
            &[("ref", choices.commit_sha), ("path", path)],
        );
        out.push_str(&format!(
            "<div><strong>Permalink:</strong> <a class=\"mono\" href=\"{}\">{}</a></div>",
            esc(&perma),
            esc(&choices.commit_sha.chars().take(12).collect::<String>())
        ));
    }
    out.push_str("</div></details>");
    out
}

fn tree_pager(
    ctx: &Ctx,
    repo_name: &str,
    reference: &str,
    path: &str,
    page_num: usize,
    total_pages: usize,
) -> String {
    if total_pages <= 1 {
        return String::new();
    }
    let mut out = String::from("<div class=\"pager\">");
    if page_num > 1 {
        let prev = ctx.action(
            repo_name,
            "tree",
            &[
                ("ref", reference),
                ("path", path),
                ("page", &(page_num - 1).to_string()),
            ],
        );
        out.push_str(&format!("<a href=\"{}\">&larr; Prev</a>", esc(&prev)));
    } else {
        out.push_str("<span class=\"disabled\">&larr; Prev</span>");
    }
    out.push_str(&format!(
        "<span class=\"disabled\">page {page_num} of {total_pages}</span>"
    ));
    if page_num < total_pages {
        let next = ctx.action(
            repo_name,
            "tree",
            &[
                ("ref", reference),
                ("path", path),
                ("page", &(page_num + 1).to_string()),
            ],
        );
        out.push_str(&format!("<a href=\"{}\">Next &rarr;</a>", esc(&next)));
    } else {
        out.push_str("<span class=\"disabled\">Next &rarr;</span>");
    }
    out.push_str("</div>");
    out
}

/// Everything the tree view needs beyond the repo/ref/path triple.
#[derive(Clone, Copy, Debug, Default)]
pub struct TreeView<'a> {
    /// 1-based page of the (paginated) directory listing.
    pub page_num: usize,
    /// Total number of pages.
    pub total_pages: usize,
    /// Total entries in the directory, when pagination is in play.
    pub total_entries: Option<usize>,
    /// What the ref switcher offers.
    pub refs: RefChoices<'a>,
    /// `.gitmodules` `path` → `url`, for gitlink entries.
    pub submodules: &'a [(String, String)],
}

/// A directory listing, with breadcrumbs, ref switcher, pager and README.
#[must_use]
pub fn tree_page(
    ctx: &Ctx,
    repo: &Repo,
    reference: &str,
    path: &str,
    entries: &[TreeEntry],
    readme: &Readme<'_>,
    view: &TreeView<'_>,
) -> String {
    let bar = crumb_bar(ctx, &repo.name, reference, path, false);
    let switcher = ref_switcher(ctx, &repo.name, "tree", reference, path, &view.refs);
    let mut rows = String::new();
    if !path.is_empty() && view.page_num == 1 {
        let mut segs: Vec<&str> = path.split('/').collect();
        segs.pop();
        let parent = segs.join("/");
        let up = ctx.action(&repo.name, "tree", &[("ref", reference), ("path", &parent)]);
        rows.push_str(&format!(
            "<tr><td colspan=\"3\"><a href=\"{}\">..</a></td></tr>",
            esc(&up)
        ));
    }
    for e in entries {
        let mut submodule_extra = String::new();
        let (url, icon) = if e.otype == "tree" {
            (
                ctx.action(&repo.name, "tree", &[("ref", reference), ("path", &e.path)]),
                "dir",
            )
        } else if e.otype == "commit" {
            // A gitlink: show the pinned sha and, when known, the upstream URL.
            let pin = format!(
                "<span class=\"mono muted\"> @ {}</span>",
                esc(&e.sha.chars().take(12).collect::<String>())
            );
            let sub_url = view
                .submodules
                .iter()
                .find(|(p, _)| *p == e.path)
                .map(|(_, u)| u.as_str());
            let link = match sub_url {
                Some(u) => match safe_external(u) {
                    Some(safe) => format!(
                        " <a href=\"{safe}\" rel=\"nofollow noopener\">{}</a>",
                        esc(u)
                    ),
                    None => format!(" <span class=\"muted\">{}</span>", esc(u)),
                },
                None => String::new(),
            };
            submodule_extra = pin + &link;
            (String::new(), "submodule")
        } else {
            (
                ctx.action(&repo.name, "blob", &[("ref", reference), ("path", &e.path)]),
                "file",
            )
        };
        let name_cell = if url.is_empty() {
            esc(&e.name)
        } else {
            format!("<a href=\"{}\">{}</a>", esc(&url), esc(&e.name))
        };
        let size = e.size.map_or_else(String::new, |s| s.to_string());
        rows.push_str(&format!(
            "<tr><td class=\"mono muted\">{}</td>\
             <td>{name_cell} <span class=\"pill\">{icon}</span>{submodule_extra}</td>\
             <td class=\"muted\" style=\"text-align:right\">{}</td></tr>",
            esc(&e.mode),
            esc(&size),
        ));
    }
    let count_note = match view.total_entries {
        Some(total) if view.total_pages > 1 => {
            format!("<div class=\"box-head muted\">{total} entries</div>")
        }
        _ => String::new(),
    };
    let table = format!(
        "<div class=\"box\">{count_note}<table class=\"list\"><thead><tr><th>Mode</th>\
         <th>Name</th><th>Size</th></tr></thead><tbody>{rows}</tbody></table></div>"
    );
    let pager = tree_pager(
        ctx,
        &repo.name,
        reference,
        path,
        view.page_num,
        view.total_pages,
    );
    let readme_box = match readme.html {
        Some(html) => format!(
            "<div class=\"box\"><div class=\"box-head\">{}</div>\
             <div class=\"box-body readme\">{html}</div></div>",
            esc(readme.name.unwrap_or("README"))
        ),
        None => String::new(),
    };
    let title = format!(
        "{}: {}",
        repo.name,
        if path.is_empty() { "/" } else { path }
    );
    page(
        ctx,
        &title,
        &(bar + &switcher + &table + &pager + &readme_box),
        Some(&repo.name),
        "tree",
        &repo.description,
    )
}

