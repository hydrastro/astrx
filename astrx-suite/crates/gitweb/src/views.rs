// --------------------------------------------------------------------------- //
// Rendering context: the mount prefix + the clock
// --------------------------------------------------------------------------- //

/// The per-request rendering context every view is parameterised on.
///
/// It carries the two values the Python reference keeps in process-wide state:
///
/// * the **reverse-proxy mount prefix** (`--url-prefix`, e.g. `/git`) that every
///   generated URL is built on — Python holds it in a `ContextVar` set at the top
///   of each request so concurrent requests cannot cross-contaminate; passing it
///   explicitly makes that impossible by construction, and
/// * the **clock** [`relative_date`] measures against. `None` means "now", which
///   is what a live server uses; a fixed value makes a view's output a pure
///   function of its inputs, which is what the cross-check tests rely on.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct Ctx {
    prefix: String,
    now: Option<f64>,
}

impl Ctx {
    /// A context mounted at `prefix` (`""` for the site root) using the live clock.
    #[must_use]
    pub fn new(prefix: &str) -> Self {
        Ctx {
            prefix: prefix.to_string(),
            now: None,
        }
    }

    /// A context mounted at `prefix` with `relative_date` pinned to `now`
    /// (epoch seconds) — deterministic rendering for tests and goldens.
    #[must_use]
    pub fn at(prefix: &str, now: f64) -> Self {
        Ctx {
            prefix: prefix.to_string(),
            now: Some(now),
        }
    }

    /// The reverse-proxy mount prefix (`""` when mounted at the site root).
    #[must_use]
    pub fn prefix(&self) -> &str {
        &self.prefix
    }

    /// The pinned clock, if any (`None` means "read the system clock").
    #[must_use]
    pub fn now(&self) -> Option<f64> {
        self.now
    }

    /// The repository-list URL — Python `u_home()`.
    #[must_use]
    pub fn home(&self) -> String {
        format!("{}/", self.prefix)
    }

    /// A repository's summary URL — Python `u_repo(name)`.
    #[must_use]
    pub fn repo(&self, name: &str) -> String {
        format!("{}/{}/", self.prefix, quote(name, ""))
    }

    /// An action URL with a query string — Python `u_action(name, action, **params)`.
    ///
    /// Parameters whose value is empty are dropped (Python drops `None` and `""`),
    /// and the rest are `urlencode`d in the order given.
    #[must_use]
    pub fn action(&self, name: &str, action: &str, params: &[(&str, &str)]) -> String {
        let mut base = format!("{}/{}/{action}", self.prefix, quote(name, ""));
        let clean: Vec<(String, String)> = params
            .iter()
            .filter(|(_, v)| !v.is_empty())
            .map(|(k, v)| ((*k).to_string(), (*v).to_string()))
            .collect();
        if !clean.is_empty() {
            base.push('?');
            base.push_str(&urlencode(&clean));
        }
        base
    }

    /// `relative_date(ts)` against this context's clock.
    fn rel(&self, ts: Option<i64>) -> String {
        relative_date(ts, self.now)
    }
}

/// Return an escaped `href` for an http(s) URL, else `None` (not linkable).
fn safe_external(url: &str) -> Option<String> {
    let probe = url.trim();
    let low = probe.to_lowercase();
    if low.starts_with("https://") || low.starts_with("http://") {
        Some(esc(probe))
    } else {
        None
    }
}

