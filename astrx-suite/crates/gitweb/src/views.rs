/// A paginated commit log for one ref.
#[must_use]
pub fn log_page(
    ctx: &Ctx,
    repo: &Repo,
    reference: &str,
    rows: &[CommitRow],
    page_num: usize,
    total_pages: usize,
) -> String {
    let header = format!(
        "<p class=\"muted\">Log for <span class=\"pill\">{}</span> \
         &mdash; page {page_num} of {}</p>",
        esc(reference),
        total_pages.max(1)
    );
    let table = if rows.is_empty() {
        "<p class=\"muted\">No commits.</p>".to_string()
    } else {
        format!(
            "<table class=\"list\"><thead><tr><th>Commit</th><th>Subject</th>\
             <th>Author</th><th>When</th></tr></thead><tbody>{}</tbody></table>",
            commit_rows(ctx, &repo.name, rows)
        )
    };
    let mut pager = String::from("<div class=\"pager\">");
    if page_num > 1 {
        let prev = ctx.action(
            &repo.name,
            "log",
            &[("ref", reference), ("page", &(page_num - 1).to_string())],
        );
        pager.push_str(&format!("<a href=\"{}\">&larr; Newer</a>", esc(&prev)));
    } else {
        pager.push_str("<span class=\"disabled\">&larr; Newer</span>");
    }
    if page_num < total_pages {
        let next = ctx.action(
            &repo.name,
            "log",
            &[("ref", reference), ("page", &(page_num + 1).to_string())],
        );
        pager.push_str(&format!("<a href=\"{}\">Older &rarr;</a>", esc(&next)));
    } else {
        pager.push_str("<span class=\"disabled\">Older &rarr;</span>");
    }
    pager.push_str("</div>");
    page(
        ctx,
        &format!("{}: log", repo.name),
        &(header + &table + &pager),
        Some(&repo.name),
        "log",
        &repo.description,
    )
}

