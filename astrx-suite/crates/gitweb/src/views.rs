/// The repository index: a no-JS name/description filter over the discovered repos.
#[must_use]
pub fn repo_list(ctx: &Ctx, repos: &[Repo], q: &str) -> String {
    let mut rows = String::new();
    for r in repos {
        let when = match r.last_commit_ts {
            Some(ts) if ts != 0 => ctx.rel(Some(ts)),
            _ => "empty".to_string(),
        };
        let kind = if r.bare { "bare" } else { "worktree" };
        let desc = esc(&r.description);
        rows.push_str(&format!(
            "<tr><td><a href=\"{}\">{}</a> <span class=\"pill\">{}</span></td>\
             <td class=\"muted\">{}</td><td class=\"muted\">{}</td></tr>",
            esc(&ctx.repo(&r.name)),
            esc(&r.name),
            esc(kind),
            if desc.is_empty() { "&mdash;" } else { &desc },
            esc(&when),
        ));
    }
    let table = if rows.is_empty() {
        let empty = if q.is_empty() {
            "No repositories found under the configured root."
        } else {
            "No repositories match that filter."
        };
        format!("<p class=\"muted\">{}</p>", esc(empty))
    } else {
        format!(
            "<table class=\"list\"><thead><tr><th>Repository</th>\
             <th>Description</th><th>Last commit</th></tr></thead><tbody>{rows}</tbody></table>"
        )
    };
    // A no-JS repository finder (form-action 'self'). Submitting filters the
    // list by name/description; this is also the target of the site-level
    // OpenSearch descriptor, so a browser can jump to a repo from the URL bar.
    let form = format!(
        "<form class=\"search\" method=\"get\" action=\"{}\" role=\"search\">\
         <input type=\"search\" name=\"q\" value=\"{}\" \
         placeholder=\"Filter repositories…\" aria-label=\"Filter repositories\">\
         <button type=\"submit\">Filter</button></form>",
        esc(&ctx.home()),
        esc(q)
    );
    let body = format!(
        "<div class=\"repo-head\"><h1>Repositories</h1></div>\
         <div class=\"desc\">Read-only browser</div>{form}{table}"
    );
    page(ctx, "Repositories", &body, None, "", "")
}

