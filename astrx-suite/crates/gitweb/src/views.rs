/// The per-repository tab strip, with `active` highlighted.
fn tabs(ctx: &Ctx, repo_name: &str, active: &str) -> String {
    let items: [(&str, &str, String); 8] = [
        ("summary", "Summary", ctx.repo(repo_name)),
        ("refs", "Refs", ctx.action(repo_name, "refs", &[])),
        ("log", "Log", ctx.action(repo_name, "log", &[])),
        ("graph", "Graph", ctx.action(repo_name, "graph", &[])),
        ("tree", "Tree", ctx.action(repo_name, "tree", &[])),
        (
            "releases",
            "Releases",
            ctx.action(repo_name, "releases", &[]),
        ),
        ("patches", "Patches", ctx.action(repo_name, "patches", &[])),
        ("search", "Search", ctx.action(repo_name, "search", &[])),
    ];
    let mut out = String::from("<nav class=\"tabs\">");
    for (key, label, url) in &items {
        let cls = if *key == active {
            " class=\"active\""
        } else {
            ""
        };
        out.push_str(&format!("<a{cls} href=\"{}\">{}</a>", esc(url), esc(label)));
    }
    out.push_str("</nav>");
    out
}

/// Wrap `body` in the full HTML document (head, header, tabs, footer).
///
/// `repo_name` selects the repository chrome (title link, description, tab
/// strip, Atom + per-repo OpenSearch autodiscovery); `None` renders the bare
/// site shell used by the repository list and the error pages.
#[must_use]
pub fn page(
    ctx: &Ctx,
    title: &str,
    body: &str,
    repo_name: Option<&str>,
    active_tab: &str,
    repo_desc: &str,
) -> String {
    let mut out = String::with_capacity(CSS.len() + body.len() + 2048);
    out.push_str("<!doctype html>");
    out.push_str("<html lang=\"en\"><head><meta charset=\"utf-8\">");
    out.push_str("<meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">");
    out.push_str("<meta name=\"referrer\" content=\"no-referrer\">");
    out.push_str(&format!("<title>{}</title>", esc(title)));
    out.push_str(&format!("<style>{CSS}</style>"));
    // Autodiscovery links, in the order the reference's `head.insert(6, …)`
    // calls leave them: the per-repo code-search descriptor, then the repo's
    // Atom feed, then the site-level (repository finder) descriptor.
    if let Some(name) = repo_name {
        let os_href = format!("{}/{}/opensearch.xml", ctx.prefix(), quote(name, ""));
        out.push_str(&format!(
            "<link rel=\"search\" type=\"application/opensearchdescription+xml\" \
             title=\"{} code\" href=\"{}\">",
            esc(name),
            esc(&os_href)
        ));
        out.push_str(&format!(
            "<link rel=\"alternate\" type=\"application/atom+xml\" \
             title=\"{} commits\" href=\"{}\">",
            esc(name),
            esc(&ctx.action(name, "atom", &[]))
        ));
    }
    out.push_str(&format!(
        "<link rel=\"search\" type=\"application/opensearchdescription+xml\" \
         title=\"gitweb repositories\" href=\"{}\">",
        esc(&format!("{}/opensearch.xml", ctx.prefix()))
    ));
    out.push_str("</head><body>");
    out.push_str("<header class=\"top\"><div class=\"wrap\">");
    out.push_str(&format!(
        "<a class=\"brand\" href=\"{}\">gitweb</a>",
        esc(&ctx.home())
    ));
    out.push_str("</div></header>");
    out.push_str("<div class=\"wrap\">");
    if let Some(name) = repo_name {
        out.push_str("<div class=\"repo-head\">");
        out.push_str(&format!(
            "<h1><a href=\"{}\">{}</a></h1>",
            esc(&ctx.repo(name)),
            esc(name)
        ));
        out.push_str("</div>");
        if !repo_desc.is_empty() {
            out.push_str(&format!("<div class=\"desc\">{}</div>", esc(repo_desc)));
        }
        out.push_str(&tabs(ctx, name, active_tab));
    }
    out.push_str(body);
    out.push_str(
        "<footer>Served by gitweb — a read-only, no-JavaScript git viewer.\
         </footer></div></body></html>",
    );
    out
}

/// The error page shown for every 4xx/5xx that renders HTML.
#[must_use]
pub fn error_page(ctx: &Ctx, code: u16, message: &str) -> String {
    let body = format!(
        "<div class=\"box\"><div class=\"box-head\">Error {code}</div>\
         <div class=\"box-body\"><p>{}</p>\
         <p><a href=\"{}\">&larr; Back to repositories</a></p>\
         </div></div>",
        esc(message),
        esc(&ctx.home())
    );
    page(ctx, &format!("Error {code}"), &body, None, "", "")
}

