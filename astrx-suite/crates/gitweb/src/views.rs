/// How the per-file history is paginated, and whether renames are followed.
#[derive(Clone, Copy, Debug, Default)]
pub struct HistoryView {
    /// 1-based page number.
    pub page_num: usize,
    /// Total pages.
    pub total_pages: usize,
    /// `--follow` (rename tracking) is on.
    pub follow: bool,
}

/// The commits touching one path, optionally following renames.
#[must_use]
pub fn history_page(
    ctx: &Ctx,
    repo: &Repo,
    reference: &str,
    path: &str,
    rows: &[CommitRow],
    view: &HistoryView,
) -> String {
    let HistoryView {
        page_num,
        total_pages,
        follow,
    } = *view;
    let bar = crumb_bar(ctx, &repo.name, reference, path, true);
    let blob_url = ctx.action(&repo.name, "blob", &[("ref", reference), ("path", path)]);
    let (toggle, toggle_label) = if follow {
        (
            ctx.action(&repo.name, "history", &[("ref", reference), ("path", path)]),
            "Disable follow",
        )
    } else {
        (
            ctx.action(
                &repo.name,
                "history",
                &[("ref", reference), ("path", path), ("follow", "1")],
            ),
            "Follow renames",
        )
    };
    let actions = format!(
        "<div class=\"pager\"><a href=\"{}\">View file</a><a href=\"{}\">{}</a></div>",
        esc(&blob_url),
        esc(&toggle),
        esc(toggle_label)
    );
    let header = format!(
        "<p class=\"muted\">History of <span class=\"mono\">{}</span> on \
         <span class=\"pill\">{}</span>{} &mdash; page {page_num} of {}</p>",
        esc(path),
        esc(reference),
        if follow {
            " <span class=\"pill\">follow</span>"
        } else {
            ""
        },
        total_pages.max(1),
    );
    let table = if rows.is_empty() {
        "<p class=\"muted\">No history for this path.</p>".to_string()
    } else {
        format!(
            "<table class=\"list\"><thead><tr><th>Commit</th><th>Subject</th>\
             <th>Author</th><th>When</th></tr></thead><tbody>{}</tbody></table>",
            commit_rows(ctx, &repo.name, rows)
        )
    };
    let follow_param = if follow { "1" } else { "" };
    let mut pager = String::from("<div class=\"pager\">");
    if page_num > 1 {
        let prev = ctx.action(
            &repo.name,
            "history",
            &[
                ("ref", reference),
                ("path", path),
                ("page", &(page_num - 1).to_string()),
                ("follow", follow_param),
            ],
        );
        pager.push_str(&format!("<a href=\"{}\">&larr; Newer</a>", esc(&prev)));
    } else {
        pager.push_str("<span class=\"disabled\">&larr; Newer</span>");
    }
    if page_num < total_pages {
        let next = ctx.action(
            &repo.name,
            "history",
            &[
                ("ref", reference),
                ("path", path),
                ("page", &(page_num + 1).to_string()),
                ("follow", follow_param),
            ],
        );
        pager.push_str(&format!("<a href=\"{}\">Older &rarr;</a>", esc(&next)));
    } else {
        pager.push_str("<span class=\"disabled\">Older &rarr;</span>");
    }
    pager.push_str("</div>");
    page(
        ctx,
        &format!("{}: history {path}", repo.name),
        &(bar + &actions + &header + &table + &pager),
        Some(&repo.name),
        "tree",
        &repo.description,
    )
}

