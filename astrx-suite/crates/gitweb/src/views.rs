/// Render `text` as a line-numbered, anchored table of escaped source lines.
///
/// `hl` holds the 1-based line numbers to highlight (the `?highlight=` range).
#[must_use]
pub fn numbered_lines(text: &str, hl: &[usize]) -> String {
    let mut lines: Vec<&str> = text.split('\n').collect();
    // Drop the trailing empty element produced by a final newline.
    if lines.last() == Some(&"") {
        lines.pop();
    }
    let mut rows = String::new();
    for (i, line) in lines.iter().enumerate() {
        let n = i + 1;
        let cls = if hl.contains(&n) { " class=\"hl\"" } else { "" };
        rows.push_str(&format!(
            "<tr id=\"L{n}\"{cls}><td class=\"lineno\"><a href=\"#L{n}\">{n}</a></td>\
             <td class=\"line\">{}</td></tr>",
            esc(line)
        ));
    }
    format!("<table class=\"code\"><tbody>{rows}</tbody></table>")
}

/// Everything the blob view needs beyond the repo/ref/path triple.
#[derive(Clone, Copy, Debug, Default)]
pub struct BlobView<'a> {
    /// The blob's size in bytes (the LFS object's size when one is served).
    pub size: u64,
    /// The decoded text, when it is being rendered inline.
    pub text: Option<&'a str>,
    /// git considers the content binary.
    pub binary: bool,
    /// The blob is over the inline-display cap.
    pub too_large: bool,
    /// Render inline as an `<img>` pointing at `/raw`.
    pub is_image: bool,
    /// 1-based line numbers to highlight.
    pub highlight: &'a [usize],
    /// What the ref switcher offers.
    pub refs: RefChoices<'a>,
    /// An LFS pointer whose object is **not** in local storage (show the pointer).
    pub lfs: Option<&'a LfsPointer>,
    /// An LFS pointer whose object **is** in local storage (real content shown).
    pub lfs_served: Option<&'a LfsPointer>,
    /// Rendered Markdown, when the blob is a Markdown document.
    pub rendered_md: Option<&'a str>,
    /// `?display=source`: show the numbered source instead of the rendering.
    pub show_source: bool,
}

/// One file: raw/blame/history actions plus the content (source, image, LFS
/// pointer, rendered Markdown, or a "too large"/"binary" notice).
#[must_use]
pub fn blob_page(
    ctx: &Ctx,
    repo: &Repo,
    reference: &str,
    path: &str,
    view: &BlobView<'_>,
) -> String {
    let bar = crumb_bar(ctx, &repo.name, reference, path, true);
    let switcher = ref_switcher(ctx, &repo.name, "blob", reference, path, &view.refs);
    let raw_url = ctx.action(&repo.name, "raw", &[("ref", reference), ("path", path)]);
    let blame_url = ctx.action(&repo.name, "blame", &[("ref", reference), ("path", path)]);
    let history_url = ctx.action(&repo.name, "history", &[("ref", reference), ("path", path)]);
    let mut actions = format!(
        "<div class=\"pager\"><a href=\"{}\">Raw</a><a href=\"{}\">Blame</a>\
         <a href=\"{}\">History</a><span class=\"disabled\">{} bytes</span></div>",
        esc(&raw_url),
        esc(&blame_url),
        esc(&history_url),
        view.size,
    );
    // When the real content of an LFS-tracked file is being served from local
    // storage, surface a small note (the oid the bytes came from).
    if let Some(served) = view.lfs_served {
        actions.push_str(&format!(
            "<p class=\"muted\">Stored with Git LFS &mdash; served from local \
             storage (oid sha256:{}&hellip;).</p>",
            esc(&served.oid.chars().take(16).collect::<String>())
        ));
    }

    let body = if let Some(lfs) = view.lfs {
        format!(
            "<div class=\"box\"><div class=\"box-head\">Git LFS pointer</div>\
             <div class=\"box-body\">\
             <p>This file is stored with Git LFS and its object is not in this \
             server's local LFS storage, so only the pointer is shown.</p>\
             <table class=\"list\"><tbody>\
             <tr><th>oid</th><td class=\"mono\">sha256:{}</td></tr>\
             <tr><th>size</th><td>{} bytes</td></tr></tbody></table>\
             <p><a href=\"{}\">Download pointer (raw)</a></p></div></div>",
            esc(&lfs.oid),
            lfs.size,
            esc(&raw_url)
        )
    } else if view.is_image {
        // CSP img-src 'self' permits this; /raw serves the correct image type.
        format!(
            "<div class=\"box\"><div class=\"box-body\" style=\"text-align:center\">\
             <img class=\"blob-img\" src=\"{}\" alt=\"{}\"></div></div>",
            esc(&raw_url),
            esc(path)
        )
    } else if view.binary {
        format!(
            "<div class=\"warn\">Binary file &mdash; {} bytes. \
             <a href=\"{}\">Download raw</a>.</div>",
            view.size,
            esc(&raw_url)
        )
    } else if view.too_large {
        format!(
            "<div class=\"warn\">File is {} bytes, larger than the inline display limit. \
             <a href=\"{}\">View raw</a>.</div>",
            view.size,
            esc(&raw_url)
        )
    } else if view.rendered_md.is_some() && !view.show_source {
        // A Markdown blob rendered, with a toggle to the raw numbered source.
        let src_url = ctx.action(
            &repo.name,
            "blob",
            &[("ref", reference), ("path", path), ("display", "source")],
        );
        format!(
            "<div class=\"pager\"><a href=\"{}\">View source</a></div>\
             <div class=\"box\"><div class=\"box-body readme\">{}</div></div>",
            esc(&src_url),
            view.rendered_md.unwrap_or("")
        )
    } else {
        let toggle = match view.rendered_md {
            Some(_) => {
                let rendered_url =
                    ctx.action(&repo.name, "blob", &[("ref", reference), ("path", path)]);
                format!(
                    "<div class=\"pager\"><a href=\"{}\">View rendered</a></div>",
                    esc(&rendered_url)
                )
            }
            None => String::new(),
        };
        toggle + &numbered_lines(view.text.unwrap_or(""), view.highlight)
    };
    page(
        ctx,
        &format!("{}: {path}", repo.name),
        &(bar + &switcher + &actions + &body),
        Some(&repo.name),
        "tree",
        &repo.description,
    )
}

