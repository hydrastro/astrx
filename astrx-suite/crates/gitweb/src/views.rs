/// Render a parsed unified diff (one `.file` block per file).
fn render_diff(files: &[DiffFile]) -> String {
    let mut out = String::new();
    for f in files {
        out.push_str(&format!(
            "<div class=\"file\"><div class=\"file-head\">\
             <span class=\"path\">{}</span><span class=\"pill\">{}</span>\
             <span class=\"stat-add\">+{}</span><span class=\"stat-del\">-{}</span></div>",
            esc(&f.display_path()),
            esc(f.status.as_str()),
            f.additions,
            f.deletions,
        ));
        if f.binary {
            out.push_str("<div class=\"box-body muted\">Binary file not shown.</div>");
        } else if f.lines.is_empty() {
            out.push_str("<div class=\"box-body muted\">No textual changes.</div>");
        } else {
            out.push_str("<table class=\"diff\"><tbody>");
            for ln in &f.lines {
                out.push_str(&format!(
                    "<tr class=\"diff-{}\"><td class=\"diff-line\">{}</td></tr>",
                    esc(ln.kind.as_str()),
                    esc(&ln.text)
                ));
            }
            out.push_str("</tbody></table>");
        }
        out.push_str("</div>");
    }
    if out.is_empty() {
        return "<p class=\"muted\">No changes (empty or merge commit).</p>".to_string();
    }
    out
}

/// git `%G?` status code → human label.
fn sig_label(status: &str) -> &'static str {
    match status {
        "G" => "good signature",
        "U" => "good signature, unknown validity",
        "X" => "good signature that has expired",
        "Y" => "good signature made by an expired key",
        "R" => "good signature made by a revoked key",
        "B" => "bad signature",
        "E" => "signature cannot be checked",
        _ => "signed",
    }
}

/// A small inline badge for the commit header (empty when unsigned).
#[must_use]
pub fn signature_badge(commit: &Commit) -> String {
    if commit.signature_verified() {
        return " <span class=\"badge-ok\" title=\"Verified signature\">Verified</span>"
            .to_string();
    }
    if commit.signature_present() {
        return " <span class=\"badge-warn\" title=\"Signature problem\">Unverified</span>"
            .to_string();
    }
    String::new()
}

/// The signature row shown in the commit metadata table.
#[must_use]
pub fn signature_detail(commit: &Commit) -> String {
    let label = sig_label(&commit.signature_status);
    let key = if commit.signing_key.is_empty() {
        String::new()
    } else {
        format!(" key {}", esc(&commit.signing_key))
    };
    if commit.signature_verified() {
        format!(
            "<span class=\"badge-ok\">Verified</span> &mdash; {}{key}",
            esc(label)
        )
    } else {
        format!("<span class=\"badge-warn\">{}</span>{key}", esc(label))
    }
}

/// One commit: metadata, signature state and the full diff.
#[must_use]
pub fn commit_page(ctx: &Ctx, repo: &Repo, commit: &Commit, files: &[DiffFile]) -> String {
    let parents: Vec<String> = commit
        .parents
        .iter()
        .map(|p| {
            format!(
                "<a class=\"mono\" href=\"{}\">{}</a>",
                esc(&ctx.action(&repo.name, "commit", &[("id", p)])),
                esc(&p.chars().take(8).collect::<String>())
            )
        })
        .collect();
    let parent_html = if parents.is_empty() {
        "<span class=\"muted\">none (root)</span>".to_string()
    } else {
        parents.join(", ")
    };
    let total_add: usize = files.iter().map(|f| f.additions).sum();
    let total_del: usize = files.iter().map(|f| f.deletions).sum();

    let mut meta = String::from("<div class=\"box\"><div class=\"box-head\">");
    meta.push_str(&format!(
        "{}{}</div><div class=\"box-body\">",
        esc(&commit.subject),
        signature_badge(commit)
    ));
    if !commit.body.is_empty() {
        meta.push_str(&format!("<pre>{}</pre>", esc(&commit.body)));
    }
    let sig_row = if commit.signature_present() {
        format!(
            "<tr><th>Signature</th><td>{}</td></tr>",
            signature_detail(commit)
        )
    } else {
        String::new()
    };
    meta.push_str(&format!(
        "<table class=\"list\"><tbody>\
         <tr><th>Commit</th><td class=\"mono\">{sha}</td></tr>\
         <tr><th>Author</th><td>{an} &lt;{ae}&gt; <span class=\"muted\">{ad}</span></td></tr>\
         <tr><th>Committer</th><td>{cn} &lt;{ce}&gt; <span class=\"muted\">{cd}</span></td></tr>\
         {sig_row}\
         <tr><th>Parents</th><td>{parent_html}</td></tr>\
         <tr><th>Tree</th><td><a href=\"{tree}\">browse</a></td></tr>\
         <tr><th>Patch</th><td><a href=\"{patch}\">download (mbox)</a></td></tr>\
         </tbody></table>\
         <p class=\"muted\">{nfiles} file(s) changed, \
         <span class=\"stat-add\">+{total_add}</span> \
         <span class=\"stat-del\">-{total_del}</span></p></div></div>",
        sha = esc(&commit.sha),
        an = esc(&commit.author_name),
        ae = esc(&commit.author_email),
        ad = esc(&commit.author_date),
        cn = esc(&commit.committer_name),
        ce = esc(&commit.committer_email),
        cd = esc(&commit.committer_date),
        tree = esc(&ctx.action(&repo.name, "tree", &[("ref", &commit.sha)])),
        patch = esc(&ctx.action(&repo.name, "commit.patch", &[("id", &commit.sha)])),
        nfiles = files.len(),
    ));
    let body = meta + &render_diff(files);
    page(
        ctx,
        &format!("{}: {}", repo.name, commit.short),
        &body,
        Some(&repo.name),
        "log",
        &repo.description,
    )
}

