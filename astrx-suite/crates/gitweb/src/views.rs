/// An Atom 1.0 feed of recent commits on `reference`.
///
/// All dynamic text goes through [`xml_escape`], which additionally drops the C0
/// control characters XML 1.0 forbids — a single such byte in a repo-derived
/// field (commit subject/author/email, or the repo description) would otherwise
/// make the whole feed non-well-formed for every reader. Links are absolute when
/// a `base_url` (`scheme://host`) is known, otherwise relative.
#[must_use]
pub fn atom_feed(
    ctx: &Ctx,
    repo: &Repo,
    reference: &str,
    rows: &[CommitRow],
    base_url: &str,
) -> String {
    let abs = |rel: &str| -> String {
        if base_url.is_empty() {
            rel.to_string()
        } else {
            format!("{base_url}{rel}")
        }
    };
    let self_link = abs(&ctx.action(&repo.name, "atom", &[("ref", reference)]));
    let repo_link = abs(&ctx.repo(&repo.name));
    let updated = atom_date(rows.first().map(|c| c.ts));
    let feed_id = if self_link.is_empty() {
        format!("urn:gitweb:{}:{reference}", repo.name)
    } else {
        self_link.clone()
    };
    let mut out = String::new();
    out.push_str("<?xml version=\"1.0\" encoding=\"utf-8\"?>");
    out.push_str("<feed xmlns=\"http://www.w3.org/2005/Atom\">");
    out.push_str(&format!(
        "<title>{}: {}</title>",
        xml_escape(&repo.name),
        xml_escape(reference)
    ));
    out.push_str(&format!("<id>{}</id>", xml_escape(&feed_id)));
    out.push_str(&format!("<updated>{}</updated>", xml_escape(&updated)));
    out.push_str(&format!(
        "<link rel=\"self\" href=\"{}\"/>",
        xml_escape(&self_link)
    ));
    out.push_str(&format!(
        "<link rel=\"alternate\" href=\"{}\"/>",
        xml_escape(&repo_link)
    ));
    out.push_str("<generator>gitweb</generator>");
    if !repo.description.is_empty() {
        out.push_str(&format!(
            "<subtitle>{}</subtitle>",
            xml_escape(&repo.description)
        ));
    }
    for c in rows {
        let entry_link = abs(&ctx.action(&repo.name, "commit", &[("id", &c.sha)]));
        out.push_str("<entry>");
        out.push_str(&format!("<title>{}</title>", xml_escape(&c.subject)));
        out.push_str(&format!(
            "<id>urn:gitweb:commit:{}</id>",
            xml_escape(&c.sha)
        ));
        out.push_str(&format!(
            "<updated>{}</updated>",
            xml_escape(&atom_date(Some(c.ts)))
        ));
        out.push_str(&format!(
            "<link rel=\"alternate\" href=\"{}\"/>",
            xml_escape(&entry_link)
        ));
        out.push_str(&format!(
            "<author><name>{}</name><email>{}</email></author>",
            xml_escape(&c.author),
            xml_escape(&c.email)
        ));
        out.push_str(&format!(
            "<summary type=\"text\">{}</summary>",
            xml_escape(&c.subject)
        ));
        out.push_str("</entry>");
    }
    out.push_str("</feed>");
    out
}

