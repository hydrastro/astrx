fn ref_box(ctx: &Ctx, repo: &Repo, rows: &[RefRow], title: &str) -> String {
    let mut body = String::new();
    for r in rows {
        body.push_str(&format!(
            "<tr><td><a href=\"{}\">{}</a></td>\
             <td class=\"mono\"><a href=\"{}\">{}</a></td>\
             <td>{}</td><td class=\"muted\">{}</td><td><a href=\"{}\">tree</a></td></tr>",
            esc(&ctx.action(&repo.name, "log", &[("ref", &r.name)])),
            esc(&r.name),
            esc(&ctx.action(&repo.name, "commit", &[("id", &r.target)])),
            esc(&r.target),
            esc(&r.subject),
            esc(&ctx.rel(Some(r.ts))),
            esc(&ctx.action(&repo.name, "tree", &[("ref", &r.name)])),
        ));
    }
    let inner = if body.is_empty() {
        format!(
            "<div class=\"box-body muted\">No {}.</div>",
            esc(&title.to_lowercase())
        )
    } else {
        format!(
            "<table class=\"list\"><thead><tr><th>Name</th><th>Commit</th>\
             <th>Subject</th><th>Updated</th><th></th></tr></thead><tbody>{body}</tbody></table>"
        )
    };
    format!(
        "<div class=\"box\"><div class=\"box-head\">{}</div>{inner}</div>",
        esc(title)
    )
}

