/// The `<tr>` rows shared by every commit listing.
fn commit_rows(ctx: &Ctx, repo_name: &str, rows: &[CommitRow]) -> String {
    let mut out = String::new();
    for c in rows {
        let url = ctx.action(repo_name, "commit", &[("id", &c.sha)]);
        out.push_str(&format!(
            "<tr><td class=\"mono\"><a href=\"{}\">{}</a></td>\
             <td>{}</td><td class=\"muted\">{}</td><td class=\"muted\">{}</td></tr>",
            esc(&url),
            esc(&c.short),
            esc(&c.subject),
            esc(&c.author),
            esc(&ctx.rel(Some(c.ts))),
        ));
    }
    out
}

/// The repository summary: default branch, clone command, latest commits, README.
#[must_use]
pub fn summary(
    ctx: &Ctx,
    repo: &Repo,
    branch: &str,
    commits: &[CommitRow],
    readme: &Readme<'_>,
    clone_url: Option<&str>,
) -> String {
    let mut parts = String::new();
    parts.push_str(
        "<div class=\"box\"><div class=\"box-head\">Overview</div><div class=\"box-body\">",
    );
    parts.push_str(&format!(
        "<p>Default branch: <span class=\"pill\">{}</span></p>",
        esc(branch)
    ));
    parts.push_str(&format!(
        "<p><a href=\"{}\">Browse commit log</a> &middot; \
         <a href=\"{}\">Browse files</a> &middot; \
         <a href=\"{}\">Branches &amp; tags</a></p>",
        esc(&ctx.action(&repo.name, "log", &[("ref", branch)])),
        esc(&ctx.action(&repo.name, "tree", &[("ref", branch)])),
        esc(&ctx.action(&repo.name, "refs", &[])),
    ));
    parts.push_str("</div></div>");
    if let Some(url) = clone_url.filter(|u| !u.is_empty()) {
        // Read-only clone transport (Git Smart HTTP). The URL is fully escaped.
        parts.push_str(&format!(
            "<div class=\"box\"><div class=\"box-head\">Clone (read-only)</div>\
             <div class=\"box-body\"><pre class=\"clone-cmd\">git clone {}</pre></div></div>",
            esc(url)
        ));
    }
    if !commits.is_empty() {
        parts.push_str(&format!(
            "<div class=\"box\"><div class=\"box-head\">Latest commits</div>\
             <table class=\"list\"><tbody>{}</tbody></table></div>",
            commit_rows(ctx, &repo.name, commits)
        ));
    }
    if let Some(html) = readme.html {
        parts.push_str(&format!(
            "<div class=\"box\"><div class=\"box-head\">{}</div>\
             <div class=\"box-body readme\">{html}</div></div>",
            esc(readme.name.unwrap_or("README"))
        ));
    }
    page(
        ctx,
        &repo.name,
        &parts,
        Some(&repo.name),
        "summary",
        &repo.description,
    )
}

