//! Server-rendered HTML views. **No JavaScript is emitted anywhere.**
//!
//! Every view is a pure function returning a complete HTML document (or, for the
//! feeds and the OpenSearch descriptors, a complete XML document) as a `String`.
//! All dynamic values pass through [`crate::markup::esc`] /
//! [`crate::markup::xml_escape`] (or the already-safe Markdown / diff renderers)
//! before they reach the output, so repository-controlled text — a branch name, a
//! filename, a commit subject — can never inject markup.
//!
//! A faithful port of the Python `gitweb.views`, cross-checked byte-identical
//! against the reference in `tests/xcheck_views.rs` (goldens regenerated by
//! `tests/regen_views_goldens.py`).
//!
//! # Purity
//!
//! The module has **zero** third-party dependencies and no network, filesystem
//! or clock access: the two pieces of ambient state the Python reference reads
//! from globals — the reverse-proxy mount prefix (a `ContextVar`) and the clock
//! [`crate::markup::relative_date`] compares against (`time.time()`) — are
//! carried explicitly in a [`Ctx`] the caller threads through. That is what makes
//! every view testable, and byte-comparable to Python, without a socket.
//!
//! # Documented divergence
//!
//! **Syntax highlighting is not ported.** In Python it is an optional Pygments
//! hook (`markup.highlight_source`) that returns `None` — falling back to escaped
//! plaintext — whenever Pygments is absent, which is always the case in the
//! zero-dependency deployment this crate targets (and is also the `Config`
//! default, `syntax_highlight = False`). [`numbered_lines`] therefore always
//! renders the escaped-plaintext form, byte-identical to the reference's default.

