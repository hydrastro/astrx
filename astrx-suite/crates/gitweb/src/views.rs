/// px per commit row (matches the `.graph-row` height).
const G_ROW_H: i64 = 24;
/// px per lane column.
const G_COL_W: i64 = 16;
/// Commit node radius.
const G_RADIUS: i64 = 4;
/// Horizontal padding inside the SVG.
const G_PAD: i64 = 8;
/// A small fixed palette cycled by lane column (presentation attributes only —
/// no inline `<style>`, no scripting; every value here is a constant).
const G_COLORS: [&str; 8] = [
    "#0969da", "#1a7f37", "#8250df", "#bf3989", "#bc4c00", "#0550ae", "#116329", "#a40e26",
];

/// One commit's position in the lane graph, as [`assign_lanes`] computes it.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct LaneNode {
    /// Row index (0 = newest commit on the page).
    pub row: usize,
    /// Lane (column) the commit's node sits in.
    pub col: usize,
    /// The commit sha.
    pub sha: String,
    /// `(parent sha, the lane that parent was assigned)`.
    pub parents: Vec<(String, usize)>,
}

/// Assign each commit a lane (column) and record its parents' lanes.
///
/// A classic column model: `lanes` holds, per column, the sha the column is
/// currently waiting to emit (or `None` when free). Each commit takes the column
/// already waiting for it (or a fresh one); its first parent inherits that column
/// and any extra parents open new columns. Pure and bounded by the page size, so
/// it is cheap and unit-testable.
///
/// Returns `(nodes, max_cols)`.
#[must_use]
pub fn assign_lanes(rows: &[GraphCommit]) -> (Vec<LaneNode>, usize) {
    let mut lanes: Vec<Option<String>> = Vec::new();
    let mut nodes: Vec<LaneNode> = Vec::new();
    let mut max_cols = 1usize;

    for (i, c) in rows.iter().enumerate() {
        let mut my_col = lanes
            .iter()
            .position(|s| s.as_deref() == Some(c.sha.as_str()));
        if my_col.is_none() {
            my_col = Some(match lanes.iter().position(Option::is_none) {
                Some(j) => j,
                None => {
                    lanes.push(None);
                    lanes.len() - 1
                }
            });
        }
        let my_col = my_col.unwrap_or(0);
        // Converging merges: free any *other* lane also waiting for this commit.
        for (j, s) in lanes.iter_mut().enumerate() {
            if j != my_col && s.as_deref() == Some(c.sha.as_str()) {
                *s = None;
            }
        }
        let mut parent_cols: Vec<(String, usize)> = Vec::new();
        if let Some(first) = c.parents.first() {
            lanes[my_col] = Some(first.clone());
            parent_cols.push((first.clone(), my_col));
            for p in &c.parents[1..] {
                let col = match lanes.iter().position(|s| s.as_deref() == Some(p.as_str())) {
                    Some(col) => col,
                    None => {
                        let col = match lanes.iter().position(Option::is_none) {
                            Some(j) => j,
                            None => {
                                lanes.push(None);
                                lanes.len() - 1
                            }
                        };
                        lanes[col] = Some(p.clone());
                        col
                    }
                };
                parent_cols.push((p.clone(), col));
            }
        } else {
            lanes[my_col] = None; // root: the lane ends here
        }
        nodes.push(LaneNode {
            row: i,
            col: my_col,
            sha: c.sha.clone(),
            parents: parent_cols,
        });
        // `lanes.len()` here is the highest column index+1 currently allocated
        // (columns can be sparse), i.e. the width this row needs.
        max_cols = max_cols.max(lanes.len());
        while lanes.last().is_some_and(Option::is_none) {
            lanes.pop();
        }
    }
    (nodes, max_cols)
}

/// Render the lane graph as inline SVG beside a column of commit rows.
///
/// Geometry is built only from integers and the fixed colour palette, so no
/// repository-derived text ever reaches an SVG attribute; the commit metadata
/// (escaped) lives in the adjacent HTML rows, which share the row height so the
/// nodes line up.
fn render_graph_svg(
    ctx: &Ctx,
    repo_name: &str,
    nodes: &[LaneNode],
    rows: &[GraphCommit],
    max_cols: usize,
) -> String {
    let n = rows.len() as i64;
    let height = n * G_ROW_H;
    let width = G_PAD * 2 + (max_cols.max(1) as i64) * G_COL_W;
    let find_node = |sha: &str| nodes.iter().find(|nd| nd.sha == sha);
    let cx = |col: usize| -> i64 { G_PAD + (col as i64) * G_COL_W + G_COL_W / 2 };
    let cy = |row: usize| -> i64 { (row as i64) * G_ROW_H + G_ROW_H / 2 };

    let mut edges = String::new();
    let mut dots = String::new();
    for nd in nodes {
        let (x0, y0) = (cx(nd.col), cy(nd.row));
        for (psha, assigned_col) in &nd.parents {
            let parent = find_node(psha);
            // Parent off this page: draw a stub to the bottom; otherwise connect
            // to where the parent node actually renders.
            let (xp, yp) = match parent {
                Some(p) => (cx(p.col), cy(p.row)),
                None => (cx(*assigned_col), height),
            };
            let color_col = parent.map_or(*assigned_col, |p| p.col);
            let color = G_COLORS[color_col % G_COLORS.len()];
            let d = if xp == x0 {
                format!("M{x0} {y0} L{xp} {yp}")
            } else {
                // Kink one row below the child, then run straight down the lane.
                let ykink = match parent {
                    Some(_) => (y0 + G_ROW_H).min(yp),
                    None => y0 + G_ROW_H,
                };
                format!("M{x0} {y0} L{xp} {ykink} L{xp} {yp}")
            };
            edges.push_str(&format!(
                "<path d=\"{d}\" fill=\"none\" stroke=\"{color}\" stroke-width=\"1.5\"/>"
            ));
        }
        let dot_color = G_COLORS[nd.col % G_COLORS.len()];
        dots.push_str(&format!(
            "<circle cx=\"{x0}\" cy=\"{y0}\" r=\"{G_RADIUS}\" \
             fill=\"{dot_color}\" stroke=\"#ffffff\" stroke-width=\"1\"/>"
        ));
    }
    let svg = format!(
        "<svg class=\"graph-svg\" width=\"{width}\" height=\"{height}\" \
         viewBox=\"0 0 {width} {height}\" xmlns=\"http://www.w3.org/2000/svg\" \
         role=\"img\" aria-label=\"commit graph\">{edges}{dots}</svg>"
    );
    let mut row_html = String::new();
    for nd in nodes {
        let Some(c) = rows.get(nd.row) else { continue };
        let url = ctx.action(repo_name, "commit", &[("id", &c.sha)]);
        row_html.push_str(&format!(
            "<div class=\"graph-row\"><a class=\"mono\" href=\"{}\">{}</a> {} \
             <span class=\"muted\">&middot; {}, {}</span></div>",
            esc(&url),
            esc(&c.short),
            esc(&c.subject),
            esc(&c.author),
            esc(&ctx.rel(Some(c.ts))),
        ));
    }
    format!("<div class=\"graph-wrap\">{svg}<div class=\"graph-rows\">{row_html}</div></div>")
}

fn graph_pager(
    ctx: &Ctx,
    repo_name: &str,
    reference: &str,
    page_num: usize,
    total_pages: usize,
) -> String {
    let mut out = String::from("<div class=\"pager\">");
    if page_num > 1 {
        let prev = ctx.action(
            repo_name,
            "graph",
            &[("ref", reference), ("page", &(page_num - 1).to_string())],
        );
        out.push_str(&format!("<a href=\"{}\">&larr; Newer</a>", esc(&prev)));
    } else {
        out.push_str("<span class=\"disabled\">&larr; Newer</span>");
    }
    if page_num < total_pages {
        let next = ctx.action(
            repo_name,
            "graph",
            &[("ref", reference), ("page", &(page_num + 1).to_string())],
        );
        out.push_str(&format!("<a href=\"{}\">Older &rarr;</a>", esc(&next)));
    } else {
        out.push_str("<span class=\"disabled\">Older &rarr;</span>");
    }
    out.push_str("</div>");
    out
}

/// The commit graph: an inline SVG lane diagram beside the commit rows.
#[must_use]
pub fn graph_page(
    ctx: &Ctx,
    repo: &Repo,
    reference: &str,
    rows: &[GraphCommit],
    page_num: usize,
    total_pages: usize,
) -> String {
    let header = format!(
        "<p class=\"muted\">Commit graph for <span class=\"pill\">{}</span> \
         &mdash; page {page_num} of {}</p>",
        esc(reference),
        total_pages.max(1)
    );
    let body = if rows.is_empty() {
        header + "<p class=\"muted\">No commits.</p>"
    } else {
        let (nodes, max_cols) = assign_lanes(rows);
        header
            + &render_graph_svg(ctx, &repo.name, &nodes, rows, max_cols)
            + &graph_pager(ctx, &repo.name, reference, page_num, total_pages)
    };
    page(
        ctx,
        &format!("{}: graph", repo.name),
        &body,
        Some(&repo.name),
        "graph",
        &repo.description,
    )
}

// --------------------------------------------------------------------------- //
// OpenSearch descriptors
// --------------------------------------------------------------------------- //
//
// `{searchTerms}` is the OpenSearch template token the browser substitutes; it
// must survive verbatim into the `template` attribute. The URL is built from
// already-safe pieces (a server-derived base, the url-prefix, a URL-quoted repo
// name) and then run through `xml_escape`, which turns the single `&` between
// query parameters into `&amp;` (required in an XML attribute) while leaving the
// `{…}` token untouched.

/// The OpenSearch template token a browser substitutes.
const SEARCH_TERMS: &str = "{searchTerms}";

/// Per-repo code-search descriptor. `base` is `scheme://host` + the url prefix.
#[must_use]
pub fn opensearch_repo(repo_name: &str, base: &str) -> String {
    let template = format!(
        "{base}/{}/search?q={SEARCH_TERMS}&type=code",
        quote(repo_name, "")
    );
    let short: String = format!("gw:{repo_name}").chars().take(16).collect();
    format!(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\
         <OpenSearchDescription xmlns=\"http://a9.com/-/spec/opensearch/1.1/\">\
         <ShortName>{}</ShortName><Description>{}</Description>\
         <InputEncoding>UTF-8</InputEncoding>\
         <Url type=\"text/html\" method=\"get\" template=\"{}\"/>\
         </OpenSearchDescription>",
        xml_escape(&short),
        xml_escape(&format!("Code search in {repo_name}")),
        xml_escape(&template),
    )
}

/// Site-level descriptor: its search targets the repository finder (home).
#[must_use]
pub fn opensearch_site(base: &str) -> String {
    let template = format!("{base}/?q={SEARCH_TERMS}");
    format!(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\
         <OpenSearchDescription xmlns=\"http://a9.com/-/spec/opensearch/1.1/\">\
         <ShortName>gitweb</ShortName>\
         <Description>Find a repository on this gitweb</Description>\
         <InputEncoding>UTF-8</InputEncoding>\
         <Url type=\"text/html\" method=\"get\" template=\"{}\"/>\
         </OpenSearchDescription>",
        xml_escape(&template)
    )
}

/// The views that take a whole [`Repo`] cannot be unit-tested here: a
/// `RepoPath` is only mintable by `gitcmd`'s confinement check, by design. Those
/// views are covered — byte-for-byte against the Python reference, over a real
/// fixture repository — in `tests/xcheck_views.rs`.
#[cfg(test)]
mod tests {
    use super::*;

    fn ctx() -> Ctx {
        Ctx::at("", 1_600_000_000.0)
    }

    #[test]
    fn url_builders_match_python() {
        let c = Ctx::new("");
        assert_eq!(c.home(), "/");
        assert_eq!(c.repo("my repo"), "/my%20repo/");
        assert_eq!(c.action("r", "log", &[]), "/r/log");
        assert_eq!(
            c.action("r", "log", &[("ref", "main"), ("page", "")]),
            "/r/log?ref=main"
        );
        assert_eq!(
            c.action("r", "blob", &[("ref", "a/b"), ("path", "x y.txt")]),
            "/r/blob?ref=a%2Fb&path=x+y.txt"
        );
        let p = Ctx::new("/git");
        assert_eq!(p.home(), "/git/");
        assert_eq!(p.repo("r"), "/git/r/");
        assert_eq!(p.action("r", "refs", &[]), "/git/r/refs");
    }

    #[test]
    fn external_submodule_urls_must_be_http() {
        assert_eq!(
            safe_external("https://example.com/x.git"),
            Some("https://example.com/x.git".to_string())
        );
        assert_eq!(safe_external("javascript:alert(1)"), None);
        assert_eq!(safe_external("git@example.com:x.git"), None);
        assert_eq!(safe_external(""), None);
    }

    #[test]
    fn error_page_escapes_and_has_no_script() {
        let html = error_page(&ctx(), 404, "<script>alert(1)</script>");
        assert!(html.starts_with("<!doctype html>"));
        assert!(html.contains("&lt;script&gt;alert(1)&lt;/script&gt;"));
        assert!(!html.contains("<script>"));
        assert!(html.ends_with("</body></html>"));
    }

    #[test]
    fn numbered_lines_escapes_and_anchors() {
        let html = numbered_lines("a = 1 < 2\n<b>\n", &[2]);
        assert!(html.contains("1 &lt; 2"));
        assert!(html.contains("id=\"L1\"><td class=\"lineno\"><a href=\"#L1\">1</a>"));
        assert!(html.contains("id=\"L2\" class=\"hl\""));
        assert!(!html.contains("<b>"));
    }

    #[test]
    fn ref_switcher_marks_the_current_ref() {
        let branches = vec!["main".to_string(), "feature".to_string()];
        let html = ref_switcher(
            &ctx(),
            "r",
            "tree",
            "main",
            "",
            &RefChoices {
                branches: &branches,
                tags: &[],
                commit_sha: "0123456789abcdef",
            },
        );
        assert!(html.contains("main &check;"));
        assert!(html.contains(">feature</a>"));
        assert!(html.contains("Permalink"));
        assert!(html.contains(">0123456789ab</a>"));
        assert!(html.contains("<span class=\"muted\">none</span>")); // no tags
    }

    #[test]
    fn assign_lanes_handles_a_merge() {
        let commit = |sha: &str, parents: &[&str]| GraphCommit {
            sha: sha.to_string(),
            short: sha[..4.min(sha.len())].to_string(),
            parents: parents.iter().map(|p| (*p).to_string()).collect(),
            author: "a".to_string(),
            ts: 0,
            subject: "s".to_string(),
        };
        let rows = vec![
            commit("m", &["a", "b"]),
            commit("a", &["root"]),
            commit("b", &["root"]),
            commit("root", &[]),
        ];
        let (nodes, max_cols) = assign_lanes(&rows);
        assert_eq!(nodes.len(), 4);
        assert_eq!(nodes[0].parents.len(), 2);
        assert_ne!(nodes[0].parents[0].1, nodes[0].parents[1].1);
        assert!(max_cols >= 2);
    }

    #[test]
    fn opensearch_descriptors_keep_the_template_token() {
        let repo = opensearch_repo("my<repo>", "http://h/git");
        assert!(repo.contains("{searchTerms}"));
        assert!(repo.contains("&amp;type=code"));
        assert!(repo.contains("my%3Crepo%3E/search"));
        assert!(!repo.contains("<repo>"));
        let site = opensearch_site("http://h");
        assert!(site.contains("template=\"http://h/?q={searchTerms}\""));
    }

    #[test]
    fn diff_rendering_escapes_every_line() {
        use crate::markup::parse_patch;
        let files = parse_patch(
            "diff --git a/<x>.txt b/<x>.txt\n\
             index 111..222 100644\n\
             --- a/<x>.txt\n\
             +++ b/<x>.txt\n\
             @@ -1 +1 @@\n\
             -<old>\n\
             +<script>alert(1)</script>\n",
        );
        let html = render_diff(&files);
        assert!(html.contains("&lt;script&gt;alert(1)&lt;/script&gt;"));
        assert!(html.contains("class=\"path\">&lt;x&gt;.txt<"));
        assert!(html.contains("class=\"stat-add\">+1<"));
        assert!(html.contains("class=\"diff-del\""));
        assert!(!html.contains("<script>"));
        assert_eq!(
            render_diff(&[]),
            "<p class=\"muted\">No changes (empty or merge commit).</p>"
        );
    }
}
