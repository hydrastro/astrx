/// A no-JS search box (a GET form; needs CSP `form-action 'self'`).
fn search_form(ctx: &Ctx, repo_name: &str, q: &str, typ: &str, reference: &str) -> String {
    let action = ctx.action(repo_name, "search", &[]);
    let mut options = String::new();
    for (value, label) in [("code", "Code"), ("log", "Commit messages")] {
        let sel = if value == typ { " selected" } else { "" };
        options.push_str(&format!(
            "<option value=\"{}\"{sel}>{}</option>",
            esc(value),
            esc(label)
        ));
    }
    let ref_hidden = if reference.is_empty() {
        String::new()
    } else {
        format!(
            "<input type=\"hidden\" name=\"ref\" value=\"{}\">",
            esc(reference)
        )
    };
    format!(
        "<form class=\"search\" method=\"get\" action=\"{}\" role=\"search\">\
         <input type=\"search\" name=\"q\" value=\"{}\" \
         placeholder=\"Search…\" aria-label=\"Search query\">\
         <select name=\"type\" aria-label=\"Search type\">{options}</select>\
         {ref_hidden}<button type=\"submit\">Search</button></form>",
        esc(&action),
        esc(q)
    )
}

fn search_code_results(
    ctx: &Ctx,
    repo_name: &str,
    reference: &str,
    matches: &[GrepMatch],
    truncated: bool,
) -> String {
    if matches.is_empty() {
        return "<p class=\"muted\">No code matches.</p>".to_string();
    }
    let mut out = String::new();
    if truncated {
        out.push_str(
            "<div class=\"warn\">Results were truncated (too many matches); \
             refine the query.</div>",
        );
    }
    out.push_str(&format!(
        "<p class=\"muted\">{} match(es).</p>",
        matches.len()
    ));
    // git grep emits all hits for a file consecutively; group preserving order.
    let mut groups: Vec<(&str, Vec<&GrepMatch>)> = Vec::new();
    for m in matches {
        match groups.last_mut() {
            Some((path, hits)) if *path == m.path => hits.push(m),
            _ => groups.push((&m.path, vec![m])),
        }
    }
    for (path, hits) in groups {
        let blob_base = ctx.action(repo_name, "blob", &[("ref", reference), ("path", path)]);
        out.push_str(&format!(
            "<div class=\"box search-file\"><div class=\"box-head\">\
             <a href=\"{}\">{}</a></div>",
            esc(&blob_base),
            esc(path)
        ));
        out.push_str("<table class=\"code grep\"><tbody>");
        for m in hits {
            // `#L<n>` is a fragment appended after the (encoded) query string.
            let line_url = format!("{blob_base}#L{}", m.lineno);
            out.push_str(&format!(
                "<tr><td class=\"lineno\"><a href=\"{}\">{}</a></td>\
                 <td class=\"line\">{}</td></tr>",
                esc(&line_url),
                m.lineno,
                esc(&m.text)
            ));
        }
        out.push_str("</tbody></table></div>");
    }
    out
}

fn search_pager(
    ctx: &Ctx,
    repo_name: &str,
    q: &str,
    reference: &str,
    page_num: usize,
    total_pages: usize,
) -> String {
    if total_pages <= 1 {
        return String::new();
    }
    let link = |page: usize| -> String {
        ctx.action(
            repo_name,
            "search",
            &[
                ("q", q),
                ("type", "log"),
                ("ref", reference),
                ("page", &page.to_string()),
            ],
        )
    };
    let mut out = String::from("<div class=\"pager\">");
    if page_num > 1 {
        out.push_str(&format!(
            "<a href=\"{}\">&larr; Newer</a>",
            esc(&link(page_num - 1))
        ));
    } else {
        out.push_str("<span class=\"disabled\">&larr; Newer</span>");
    }
    out.push_str(&format!(
        "<span class=\"disabled\">page {page_num} of {total_pages}</span>"
    ));
    if page_num < total_pages {
        out.push_str(&format!(
            "<a href=\"{}\">Older &rarr;</a>",
            esc(&link(page_num + 1))
        ));
    } else {
        out.push_str("<span class=\"disabled\">Older &rarr;</span>");
    }
    out.push_str("</div>");
    out
}

/// Everything the search view needs beyond the query/type/ref triple.
#[derive(Clone, Copy, Debug, Default)]
pub struct SearchView<'a> {
    /// `git grep` hits, when the code vertical ran.
    pub code_matches: Option<&'a [GrepMatch]>,
    /// The grep result was clipped by one of the caps.
    pub code_truncated: bool,
    /// Commit rows, when the message vertical ran.
    pub log_rows: Option<&'a [CommitRow]>,
    /// 1-based page of the message-search results.
    pub page_num: usize,
    /// Total pages of message-search results.
    pub total_pages: usize,
    /// The query was empty, too long, or contained an invalid character.
    pub invalid: bool,
}

/// The search page: the form plus either code hits or matching commit messages.
#[must_use]
pub fn search_page(
    ctx: &Ctx,
    repo: &Repo,
    q: &str,
    typ: &str,
    reference: &str,
    view: &SearchView<'_>,
) -> String {
    let mut parts = format!(
        "<p class=\"muted\">Searching <span class=\"pill\">{}</span> \
         &mdash; literal (fixed-string) matching.</p>",
        esc(reference)
    );
    parts.push_str(&search_form(ctx, &repo.name, q, typ, reference));
    if view.invalid {
        parts.push_str(
            "<div class=\"warn\">Query is empty, too long, or contains an \
             invalid character.</div>",
        );
    } else if q.is_empty() {
        parts.push_str(
            "<p class=\"muted\">Enter a term. <strong>Code</strong> searches file \
             contents at this ref; <strong>Commit messages</strong> searches log \
             messages.</p>",
        );
    } else if typ == "log" {
        let rows = view.log_rows.unwrap_or(&[]);
        if rows.is_empty() {
            parts.push_str("<p class=\"muted\">No commit messages match.</p>");
        } else {
            parts.push_str(&format!(
                "<table class=\"list\"><thead><tr><th>Commit</th><th>Subject</th>\
                 <th>Author</th><th>When</th></tr></thead><tbody>{}</tbody></table>",
                commit_rows(ctx, &repo.name, rows)
            ));
            parts.push_str(&search_pager(
                ctx,
                &repo.name,
                q,
                reference,
                view.page_num,
                view.total_pages,
            ));
        }
    } else {
        parts.push_str(&search_code_results(
            ctx,
            &repo.name,
            reference,
            view.code_matches.unwrap_or(&[]),
            view.code_truncated,
        ));
    }
    page(
        ctx,
        &format!("{}: search", repo.name),
        &parts,
        Some(&repo.name),
        "search",
        &repo.description,
    )
}

